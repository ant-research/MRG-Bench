    def get_all_possible_queries(self) -> list[dict]:
        all_nodes = set()
        for u, v in self.edges.keys():
            all_nodes.add(u)
            all_nodes.add(v)
        sorted_nodes = sorted(list(all_nodes))
        
        all_paths = []

        def dfs(current_path):
            if len(current_path) >= 2:
                all_paths.append(current_path[:])
            
            last_node = current_path[-1]
            for neighbor in sorted_nodes:
                if neighbor in current_path:
                    continue
                if (last_node, neighbor) in self.edges:
                    dfs(current_path + [neighbor])

        for node in sorted_nodes:
            dfs([node])

        queries = []
        for nodes in all_paths:
            path_str = "-".join(nodes)
            
            display_val = self._calculate_display_value(nodes)
            queries.append({
                "query": f"<query_display>{path_str}</query_display>",
                "answer": str(display_val)
            })
            
            mileage_val = self._calculate_mileage(nodes)
            queries.append({
                "query": f"<query_mileage>{path_str}</query_mileage>",
                "answer": str(mileage_val)
            })
            
            feature_val = self._get_path_features(nodes)
            queries.append({
                "query": f"<query_feature>{path_str}</query_feature>",
                "answer": str(feature_val)
            })
            
        return queries

