    def _validate_path(self, nodes):
        if len(nodes) != len(set(nodes)):
            return False
        
        for i in range(len(nodes) - 1):
            if (nodes[i], nodes[i+1]) not in self.edges:
                return False
        
        return True

    def _calculate_mileage(self, nodes):
        mileage = 0
        for i in range(len(nodes) - 1):
            weight, _ = self.edges[(nodes[i], nodes[i+1])]
            mileage += weight
        return mileage

